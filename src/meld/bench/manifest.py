"""Benchmark manifest: dev / cal / test splits strictly disjoint by source item.

Each source item lands in at most one split, so a threshold, predicate or prompt
chosen on dev or cal never sees an item of test. Official splits are honoured:
items from a source's official test split go only to test, items from its
official dev/train pool only to dev or cal (leftovers are dropped, never moved
to test); sources without an official split fill dev, then cal, then test (SICK: cal, then dev). A
test pair whose text also occurs in dev or cal is dropped. At most ``cap`` pairs
per source item per stratum per split (one item must not dominate a stratum).
Items are shuffled by one generator per source (seeded with seed and source), so adding or
removing a source never moves another source's pairs. Deterministic given the seed; the manifest hash pins the exact benchmark.
"""
