SPLITS = ("dev", "cal", "test")

# Sources whose items fill cal before dev: SICK's dev is carved from what would otherwise be test, so
# its cal is the same with or without a dev split.
CAL_FIRST = {"sick"}


def _norm(t: str) -> str:
    return " ".join(t.lower().split())


def build_manifest(pairs: List[Pair], *, seed: int, sizes=SIZES, licences=SOURCES) -> dict:
    for src in sorted({p.source for p in pairs}):
        lic = licences.get(src) or {}
        if not lic.get("licence") or not lic.get("url"):
            raise ValueError(f"no licence recorded for source {src!r}; refusing it")
    missing = {p.stratum for p in pairs} - set(sizes)
    if missing:
        raise ValueError(f"no sizes for strata {sorted(missing)}")

    by_item = defaultdict(list)
    for p in sorted(pairs, key=lambda p: p.pair_id):
        by_item[p.source_item_id].append(p)
    items = []
    for src in sorted({p.source for p in pairs}):       # one generator per source: adding a source moves no other
        rng = random.Random(f"{seed}:{src}")
        its = sorted(it for it in by_item if by_item[it][0].source == src)
        rng.shuffle(its)
        for it in its:
            rng.shuffle(by_item[it])
        items += its

    def target(split, st):
        v = sizes[st][split]
        return math.inf if v is None else v

    have, chosen = Counter(), {}

    def take(split, ps):
        per = Counter()
        for p in ps:
            if per[p.stratum] < (sizes[p.stratum]["cap"] or math.inf) and have[(split, p.stratum)] < target(split, p.stratum):
                chosen[p.pair_id] = (split, p)
                have[(split, p.stratum)] += 1
                per[p.stratum] += 1
        return bool(per)

    assigned = set()
    for it in items:                                    # pass 1: dev and cal
        ps = by_item[it]
        if any(p.origin_split == "test" for p in ps):
            continue
        for split in (("cal", "dev") if ps[0].source in CAL_FIRST else ("dev", "cal")):
            if any(have[(split, p.stratum)] < target(split, p.stratum) for p in ps):
                if take(split, ps):
                    assigned.add(it)
                break
    held = {_norm(t) for _, p in chosen.values() for t in (p.text_a, p.text_b)}
    for it in items:                                    # pass 2: test
        ps = by_item[it]
        if it in assigned or any(p.origin_split == "dev" for p in ps):
            continue
        take("test", [p for p in ps if _norm(p.text_a) not in held and _norm(p.text_b) not in held])

    rows = sorted((dict(p.to_dict(), split=s) for s, p in chosen.values()),
                  key=lambda r: (SPLITS.index(r["split"]), r["stratum"], r["pair_id"]))
    counts = {s: dict(sorted(Counter(r["stratum"] for r in rows if r["split"] == s).items())) for s in SPLITS}
    return {"seed": seed, "sources": {s: licences[s] for s in sorted({r["source"] for r in rows})},
            "counts": counts, "notes": NOTES, "pairs": rows}


def manifest_hash(manifest: dict) -> str:
    blob = json.dumps(manifest, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")
    return hashlib.sha256(blob).hexdigest()


def record_identity(manifest: dict, provenance_path: str, *, manifest_path: str, files: Dict[str, str]) -> dict:
    """Write the benchmark identity into the G0 provenance file (other entries kept)."""
    data = {}
    if os.path.exists(provenance_path):
        with open(provenance_path, encoding="utf-8") as fh:
            data = json.load(fh)
    entry = {"name": "MELD claim-pair benchmark", "manifest_sha256": manifest_hash(manifest),
             "manifest_path": manifest_path, "seed": manifest["seed"], "n_pairs": len(manifest["pairs"]),
             "counts": manifest["counts"], "sources": manifest["sources"], "files": files}
    data["meld_claimpair"] = entry
    with open(provenance_path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return entry
